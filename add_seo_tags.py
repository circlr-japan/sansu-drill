def build_faq_schema(faqs):
    items = []
    for q, a in faqs:
        items.append({
            "@type": "Question",
            "name": q,
            "acceptedAnswer": {
                "@type": "Answer",
                "text": a
            }
        })
    schema = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": items
    }
    return f'<script type="application/ld+json">\n{json.dumps(schema, ensure_ascii=False, indent=2)}\n</script>'


def build_ogp_tags(filename, title, description):
    url = f"{BASE_URL}/{filename}"
    # titleからサイト名を除去
    clean_title = title.split(" | ")[0] if " | " in title else title
    return f"""<meta property="og:type" content="article">
<meta property="og:title" content="{clean_title}">
<meta property="og:description" content="{description}">
<meta property="og:url" content="{url}">
<meta property="og:site_name" content="{SITE_NAME}">
<meta property="og:image" content="{DEFAULT_IMAGE}">
<meta property="og:locale" content="ja_JP">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{clean_title}">
<meta name="twitter:description" content="{description}">
<meta name="twitter:image" content="{DEFAULT_IMAGE}">"""


def process_file(filepath, filename, page_data):
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    changed = False

    # 1. canonicalのバグ修正（05_などのプレフィックスを除去）
    wrong_canonical = re.search(r'<link rel="canonical" href="https://www\.nijumaru-drill\.com/[0-9]+_[^"]+"/>', content)
    if wrong_canonical:
        correct_canonical = f'<link rel="canonical" href="{BASE_URL}/{filename}">'
        content = re.sub(r'<link rel="canonical" href="https://www\.nijumaru-drill\.com/[0-9]+_[^"]+"/?>', correct_canonical, content)
        print(f"  🔧 canonicalバグ修正: {filename}")
        changed = True

    # 2. OGPタグ追加（未追加の場合のみ）
    if 'og:title' not in content:
        ogp = build_ogp_tags(filename, page_data["title"], page_data["description"])
        # </head>の直前に挿入
        content = content.replace('</head>', f'{ogp}\n</head>', 1)
        print(f"  ✅ OGPタグ追加: {filename}")
        changed = True
    else:
        print(f"  スキップ（OGP済み）: {filename}")

    # 3. FAQスキーマ追加（未追加の場合のみ）
    if 'FAQPage' not in content:
        faq_schema = build_faq_schema(page_data["faqs"])
        # </head>の直前に挿入
        content = content.replace('</head>', f'{faq_schema}\n</head>', 1)
        print(f"  ✅ FAQスキーマ追加: {filename}")
        changed = True
    else:
        print(f"  スキップ（FAQ済み）: {filename}")

    if changed:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

    return changed


def main():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    updated = 0

    for filename, page_data in PAGES.items():
        filepath = os.path.join(base_dir, filename)
        if not os.path.exists(filepath):
            print(f"  ❌ ファイルなし: {filename}")
            continue
        print(f"\n📄 {filename}")
        if process_file(filepath, filename, page_data):
            updated += 1

    print(f"\n🎉 完了: {updated}ページを更新しました")


if __name__ == "__main__":
    main()
