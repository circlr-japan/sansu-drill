today = datetime.date.today().strftime("%Y-%m-%d")
published = []

for filename, data in ARTICLES.items():
    draft_path = os.path.join(BASE_DIR, "drafts", data["draft"])
    dest_path = os.path.join(BASE_DIR, filename)

    if not os.path.exists(draft_path):
        print(f"❌ ドラフトなし: {data['draft']}")
        continue

    # コピー
    shutil.copy2(draft_path, dest_path)

    # canonical修正
    with open(dest_path, "r", encoding="utf-8") as f:
        content = f.read()

    num_prefix = data["draft"].split("_")[0]
    content = re.sub(
        rf'canonical" href="https://www\.nijumaru-drill\.com/{num_prefix}_{filename}',
        f'canonical" href="https://www.nijumaru-drill.com/{filename}',
        content
    )

    # FAQ JSON-LD
    faq_items = [{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in data["faq"]]
    faq_schema = json.dumps({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": faq_items}, ensure_ascii=False, indent=2)
    faq_tag = f'<script type="application/ld+json">\n{faq_schema}\n</script>'

    # OGP
    url = f"https://www.nijumaru-drill.com/{filename}"
    ogp = f'''<meta property="og:title" content="{data['title']}">
<meta property="og:description" content="{data['desc']}">
<meta property="og:url" content="{url}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="にじゅうまる。算数ドリル">
<meta property="og:image" content="https://www.nijumaru-drill.com/ogp-default.png">
<meta property="og:locale" content="ja_JP">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{data['title']}">
<meta name="twitter:description" content="{data['desc']}">
<meta name="twitter:image" content="https://www.nijumaru-drill.com/ogp-default.png">'''

    if "FAQPage" not in content:
        content = content.replace("</head>", ogp + "\n" + faq_tag + "\n</head>", 1)

    with open(dest_path, "w", encoding="utf-8") as f:
        f.write(content)

    published.append((filename, today))
    print(f"✅ 公開: {filename}")

# sitemap更新
sitemap_path = os.path.join(BASE_DIR, "sitemap.xml")
with open(sitemap_path, "r", encoding="utf-8") as f:
    sitemap = f.read()

new_entries = ""
for filename, date in published:
    url = f"https://www.nijumaru-drill.com/{filename}"
    if url not in sitemap:
        new_entries += f'  <url><loc>{url}</loc><lastmod>{date}</lastmod><changefreq>monthly</changefreq><priority>0.7</priority></url>\n'

if new_entries:
    sitemap = sitemap.replace("</urlset>", new_entries + "</urlset>")
    with open(sitemap_path, "w", encoding="utf-8") as f:
        f.write(sitemap)
    print(f"\n✅ sitemap更新: {len(published)}件追加")

print(f"\n🎉 {len(published)}記事を公開しました")
